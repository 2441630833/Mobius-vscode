/*---------------------------------------------------------------------------------------------
 *  Mobius — auto-route prefers `.agents/skills` (especially skills/auto)
 *--------------------------------------------------------------------------------------------*/

import assert from 'assert';
import { URI } from '../../../../../base/common/uri.js';
import { ensureNoDisposablesAreLeakedInTestSuite } from '../../../../../base/test/common/utils.js';
import { IAgentSkill, PromptsStorage } from '../../../chat/common/promptSyntax/service/promptsService.js';
import {
	isMobiusAgentsFolderSkill,
	isMobiusAutoGeneratedSkill,
	selectAutoRoutedSkills,
	simulateLexicalSkillRouting,
} from '../../browser/continueSkillsContext.js';

function skill(path: string, name: string, description: string): IAgentSkill {
	return {
		uri: URI.file(path),
		storage: PromptsStorage.local,
		name,
		description,
		disableModelInvocation: false,
		userInvocable: true,
	};
}

suite('Mobius generated skills auto-route', () => {

	ensureNoDisposablesAreLeakedInTestSuite();

	test('detects .agents/skills/auto as generated', () => {
		assert.strictEqual(isMobiusAutoGeneratedSkill(URI.file('/proj/.agents/skills/auto/chip-uart/SKILL.md')), true);
		assert.strictEqual(isMobiusAgentsFolderSkill(URI.file('/proj/.agents/skills/manual-one/SKILL.md')), true);
		assert.strictEqual(isMobiusAutoGeneratedSkill(URI.file('/home/me/.claude/skills/frontend-design/SKILL.md')), false);
		assert.strictEqual(isMobiusAgentsFolderSkill(URI.file('/home/me/.claude/skills/qa/SKILL.md')), false);
	});

	test('generated skill with overlap occupies an Auto-routed slot over Claude locals', () => {
		const claudeUi = skill('/home/me/.claude/skills/frontend-design/SKILL.md', 'frontend-design', 'Use when building web components and pages');
		const claudeQa = skill('/home/me/.claude/skills/qa/SKILL.md', 'qa', 'Use when testing and verifying the app');
		const claudeVerify = skill('/home/me/.claude/skills/verification-before-completion/SKILL.md', 'verification-before-completion', 'Use when verifying work before completion');
		const generated = skill(
			'/proj/.agents/skills/auto/chip-page-layout/SKILL.md',
			'chip-page-layout',
			'Use when designing Chip mode pages 页面 界面',
		);

		const result = simulateLexicalSkillRouting('帮我设计个新页面', [claudeUi, claudeQa, claudeVerify, generated]);
		assert.ok(result.routed.includes('chip-page-layout'), `routed=${result.routed.join(',')}`);
		assert.strictEqual(result.routed[0], 'chip-page-layout');
	});

	test('unrelated generated skill is not forced into Auto-routed', () => {
		const claudeUi = skill('/home/me/.claude/skills/frontend-design/SKILL.md', 'frontend-design', 'Use when building web components and pages');
		const generated = skill(
			'/proj/.agents/skills/auto/k8s-rollout/SKILL.md',
			'k8s-rollout',
			'Use when rolling kubernetes clusters',
		);
		const result = simulateLexicalSkillRouting('帮我设计个新页面', [claudeUi, generated]);
		assert.ok(!result.routed.includes('k8s-rollout'), `routed=${result.routed.join(',')}`);
		assert.ok(result.routed.includes('frontend-design'), `routed=${result.routed.join(',')}`);
	});

	test('generic Claude UI skill still auto-routes when no .agents skill exists', () => {
		const claudeUi = skill('/home/me/.claude/skills/frontend-design/SKILL.md', 'frontend-design', 'Use when building web components and pages');
		const result = simulateLexicalSkillRouting('帮我设计个新页面', [claudeUi]);
		assert.deepStrictEqual(result.routed, ['frontend-design']);
	});

	test('selectAutoRoutedSkills reserves first slot for generated skill', () => {
		const claude = skill('/home/me/.claude/skills/frontend-design/SKILL.md', 'frontend-design', 'ui');
		const generated = skill('/proj/.agents/skills/auto/foo/SKILL.md', 'foo', 'foo');
		const picked = selectAutoRoutedSkills(
			[
				{ uri: claude.uri, name: claude.name, score: 20 },
				{ uri: generated.uri, name: generated.name, score: 5 },
			],
			3,
		);
		assert.strictEqual(picked[0].name, 'foo');
		assert.ok(picked.some(p => p.name === 'frontend-design'));
	});
});
